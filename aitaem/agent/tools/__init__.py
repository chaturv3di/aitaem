"""Tool groups, and the `artifact_tool` wrapper every tool goes through.

A tool body returns a `ToolOutput` describing its payload; `artifact_tool` writes the artifact
and hands the model a small `ToolResult` (artifact ID, status, summary, and a few facts).
"""

from __future__ import annotations

import functools
import inspect
import uuid
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

import ibis
import pyarrow as pa
import sqlglot
from pydantic import BaseModel
from pydantic_core import to_jsonable_python
from pydantic_ai import RunContext
from pydantic_ai.exceptions import (
    ApprovalRequired,
    CallDeferred,
    ModelRetry,
    RunCancelled,
    UsageLimitExceeded,
)

from aitaem.agent.artifacts import ArtifactRef, Kind, ProducedBy
from aitaem.agent.deps import SessionDeps
from aitaem.agent.trace import Status

# pydantic-ai control flow passes through the wrapper untouched.
_PASS_THROUGH = (ModelRetry, CallDeferred, ApprovalRequired, RunCancelled, UsageLimitExceeded)


class ToolResult(BaseModel):
    """What a tool returns to the model: never rows, only the artifact ID and a few facts."""

    artifact_id: str
    status: Status
    summary: str
    facts: dict[str, Any] = {}


@dataclass
class ToolOutput:
    """What a tool body returns: the payload to store and the facts to show the model."""

    payload: Any
    kind: Kind
    type_tag: str
    summary: str
    parents: list[str] = field(default_factory=list)
    status: Status = Status.ok
    facts: dict[str, Any] = field(default_factory=dict)


def _store(ctx: RunContext[SessionDeps], name: str, out: ToolOutput) -> ToolResult:
    by = ProducedBy(tool=name, call_id=ctx.tool_call_id, turn=ctx.deps.turn, role=ctx.deps.role)
    ref = ctx.deps.store.put(
        out.kind,
        out.payload,
        type_tag=out.type_tag,
        summary=out.summary,
        produced_by=by,
        parents=out.parents,
        status=out.status,
    )
    return ToolResult(artifact_id=ref.id, status=out.status, summary=ref.summary, facts=out.facts)


def _store_error(ctx: RunContext[SessionDeps], name: str, exc: Exception) -> ToolResult:
    message = f"{type(exc).__name__}: {exc}"
    out = ToolOutput({"error": message}, "object", "error", message, status=Status.error)
    return _store(ctx, name, out)


def artifact_tool(fn: Callable[..., Any]) -> Callable[..., Any]:
    """Wrap a tool body so each call writes one artifact and returns a `ToolResult`.

    The body takes `RunContext[SessionDeps]` first and returns a `ToolOutput`. When it raises,
    the wrapper writes an `error` artifact with the message and returns an `error` result.
    """
    name = fn.__name__

    if inspect.iscoroutinefunction(fn):

        @functools.wraps(fn)
        async def async_wrapper(
            ctx: RunContext[SessionDeps], *args: Any, **kwargs: Any
        ) -> ToolResult:
            try:
                out = await fn(ctx, *args, **kwargs)
            except _PASS_THROUGH:
                raise
            except Exception as e:  # noqa: BLE001
                return _store_error(ctx, name, e)
            return _store(ctx, name, out)

        return async_wrapper

    @functools.wraps(fn)
    def wrapper(ctx: RunContext[SessionDeps], *args: Any, **kwargs: Any) -> ToolResult:
        try:
            out = fn(ctx, *args, **kwargs)
        except _PASS_THROUGH:
            raise
        except Exception as e:  # noqa: BLE001
            return _store_error(ctx, name, e)
        return _store(ctx, name, out)

    return wrapper


def tabular(ctx: RunContext[SessionDeps], artifact_id: str) -> tuple[ArtifactRef, ibis.Table]:
    """Return the record and the Ibis table of a `table` or `ibis` artifact."""
    ref = ctx.deps.store.get(artifact_id)
    if ref.kind not in ("table", "ibis"):
        raise ValueError(
            f"artifact {artifact_id} is a {ref.kind}; this tool takes a table or ibis artifact"
        )
    return ref, ctx.deps.store.read(artifact_id)


def rows(arrow: pa.Table) -> list[dict[str, Any]]:
    """Return an Arrow table's rows as JSON-ready dicts (dates as ISO strings)."""
    return to_jsonable_python(arrow.to_pylist())


# ── query helpers carried over from v2 ──────────────────────────────────────


def reject_unsafe_filter(filter_sql: str, dialect: str) -> str:
    """Return a filter regenerated by sqlglot, after checking it is one predicate with no subquery.

    The source table is pinned by the caller, but a subquery could read any other table under the
    connection's credentials. Statement stacking and paren breakout fail to parse; splicing the
    regenerated SQL neutralizes trailing comments.
    """
    try:
        parsed = sqlglot.parse_one(filter_sql, into=sqlglot.exp.Condition, dialect=dialect)
    except Exception as exc:
        raise ValueError(f"filter is not a valid SQL predicate: {exc}") from exc
    if list(parsed.find_all(sqlglot.exp.Subquery, sqlglot.exp.Select)):
        raise ValueError("filter must not contain subqueries")
    return parsed.sql(dialect=dialect)


def apply_filter(table: ibis.Table, filter_sql: str | None, dialect: str) -> ibis.Table:
    """Apply a checked SQL predicate to a table as a WHERE clause."""
    if filter_sql is None:
        return table
    safe = reject_unsafe_filter(filter_sql, dialect)
    alias = f"_src_{uuid.uuid4().hex[:8]}"
    return table.alias(alias).sql(f"SELECT * FROM {alias} WHERE {safe}")


def distribution_agg(table: ibis.Table, column: str, group_by: list[str] | None) -> ibis.Table:
    """Build one aggregate query of a column's distribution, grouped by `group_by`.

    Numeric columns get count, null_count, min, max, mean, std, and approximate p25/median/p75
    (exact quantiles are unimplemented on BigQuery); other columns get count, null_count, min,
    max, and distinct_count.
    """
    col = table[column]
    aggs: dict[str, Any] = {
        "count": col.count(),
        "null_count": col.isnull().sum(),
        "min_val": col.min(),
        "max_val": col.max(),
    }
    if col.type().is_numeric():
        aggs.update(
            mean=col.mean(),
            std=col.std(),
            p25=col.approx_quantile(0.25),
            median=col.approx_quantile(0.5),
            p75=col.approx_quantile(0.75),
        )
    else:
        aggs["distinct_count"] = col.nunique()
    if group_by:
        return table.group_by(group_by).aggregate(**aggs)
    return table.aggregate(**aggs)


def stringify_bounds(arrow: pa.Table) -> pa.Table:
    """Cast `min_val` and `max_val` to strings (ISO-8601 for temporal values)."""
    for name in ("min_val", "max_val"):
        if name in arrow.column_names:
            values = [
                None if v is None else (v.isoformat() if hasattr(v, "isoformat") else str(v))
                for v in arrow[name].to_pylist()
            ]
            arrow = arrow.set_column(
                arrow.column_names.index(name), name, pa.array(values, pa.string())
            )
    return arrow


